import http from 'http';
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
import puppeteer from 'puppeteer-core';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const mediaDir = path.join(rootDir, 'public', 'media');
const videoPath = path.join(mediaDir, 'hero-bg.mp4');
const indexHtmlPath = path.join(rootDir, 'index.html');
const heroMediaJsPath = path.join(rootDir, 'src', 'data', 'heroMedia.js');
const CHROME_PATH = process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';

if (!fs.existsSync(videoPath)) {
  console.error('Missing video file:', videoPath);
  process.exit(1);
}

// Compute 8-char content hash from hero-bg.mp4
const hash = crypto
  .createHash('sha256')
  .update(fs.readFileSync(videoPath))
  .digest('hex')
  .slice(0, 8);

const posterFileName = `hero-poster.${hash}.webp`;
const posterOutPath = path.join(mediaDir, posterFileName);
const posterPublicUrl = `/media/${posterFileName}`;

function startVideoServer(port) {
  const stat = fs.statSync(videoPath);
  const server = http.createServer((req, res) => {
    if (req.url === '/hero-bg.mp4') {
      const range = req.headers.range;
      if (range) {
        const parts = range.replace(/bytes=/, '').split('-');
        const start = parseInt(parts[0], 10);
        const end = parts[1] ? parseInt(parts[1], 10) : stat.size - 1;
        res.writeHead(206, {
          'Content-Range': `bytes ${start}-${end}/${stat.size}`,
          'Accept-Ranges': 'bytes',
          'Content-Length': end - start + 1,
          'Content-Type': 'video/mp4',
        });
        fs.createReadStream(videoPath, { start, end }).pipe(res);
      } else {
        res.writeHead(200, {
          'Content-Length': stat.size,
          'Content-Type': 'video/mp4',
        });
        fs.createReadStream(videoPath).pipe(res);
      }
      return;
    }

    res.writeHead(200, { 'Content-Type': 'text/html' });
    res.end(`<!DOCTYPE html>
<html>
<body style="margin:0;background:#0b0f17;">
  <video id="v" muted playsinline preload="auto" src="/hero-bg.mp4"></video>
  <script>
    window.grabFrame = () => new Promise((resolve, reject) => {
      const v = document.getElementById('v');
      const onReady = () => {
        const targetTime = Math.min(1.5, Math.max(0.2, (v.duration || 3) * 0.25));
        v.currentTime = targetTime;
      };
      v.addEventListener('seeked', () => {
        const w = 1280;
        const h = 720;
        const canvas = document.createElement('canvas');
        canvas.width = w;
        canvas.height = h;
        const ctx = canvas.getContext('2d');
        const vw = v.videoWidth || 1280;
        const vh = v.videoHeight || 720;
        const scale = Math.max(w / vw, h / vh);
        const dw = vw * scale;
        const dh = vh * scale;
        const dx = (w - dw) * 0.5;
        const dy = (h - dh) * 0.5;
        ctx.drawImage(v, dx, dy, dw, dh);
        resolve({
          dataUrl: canvas.toDataURL('image/webp', 0.85),
          videoWidth: vw,
          videoHeight: vh,
          duration: v.duration,
          capturedAt: v.currentTime
        });
      }, { once: true });
      v.addEventListener('error', () => reject(new Error('Video load failed')), { once: true });
      if (v.readyState >= 1) onReady();
      else v.addEventListener('loadedmetadata', onReady, { once: true });
    });
  </script>
</body>
</html>`);
  });

  return new Promise((resolve) => server.listen(port, '127.0.0.1', () => resolve(server)));
}

async function run() {
  const port = 5241;
  const server = await startVideoServer(port);
  const browser = await puppeteer.launch({
    executablePath: CHROME_PATH,
    headless: 'new',
    args: ['--no-sandbox'],
  });

  try {
    const page = await browser.newPage();
    await page.goto(`http://127.0.0.1:${port}/`, { waitUntil: 'domcontentloaded' });
    const result = await page.evaluate(() => window.grabFrame());

    const base64 = result.dataUrl.replace(/^data:image\/webp;base64,/, '');
    const buf = Buffer.from(base64, 'base64');

    // Remove older hero-poster*.webp files so no stale posters linger
    for (const file of fs.readdirSync(mediaDir)) {
      if (/^hero-poster(\.[a-f0-9]+)?\.webp$/i.test(file) && file !== posterFileName) {
        fs.unlinkSync(path.join(mediaDir, file));
      }
    }

    fs.writeFileSync(posterOutPath, buf);

    // Update single-source JS constant
    fs.writeFileSync(
      heroMediaJsPath,
      `// Auto-generated by scripts/generate_poster.mjs — do not edit manually\nexport const HERO_POSTER_URL = '${posterPublicUrl}';\n`
    );

    // Update preload href in index.html
    const html = fs.readFileSync(indexHtmlPath, 'utf8');
    const updatedHtml = html.replace(
      /(<link\s+rel="preload"\s+as="image"\s+href=")[^"]+("\s+type="image\/webp"[^>]*>)/i,
      `$1${posterPublicUrl}$2`
    );
    fs.writeFileSync(indexHtmlPath, updatedHtml);

    console.log(
      JSON.stringify({
        posterFileName,
        posterPublicUrl,
        bytes: buf.length,
        videoWidth: result.videoWidth,
        videoHeight: result.videoHeight,
        duration: Number(result.duration.toFixed(2)),
        capturedAt: Number(result.capturedAt.toFixed(2)),
      })
    );
  } finally {
    await browser.close();
    server.close();
  }
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
